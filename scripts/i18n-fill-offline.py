#!/usr/bin/env python3
"""Create first-pass, offline translations for authored API literals on the feature branch.

Machine translations are a DRAFT, never proof of native-speaker review.
This script does not modify API/gameplay sources or player-authored stories.
"""
import json
import re
import sys
from pathlib import Path

from argostranslate import package, translate
from unidecode import unidecode

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "apps/web/src/i18n.tsx"
CANDIDATES = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/casefiles-i18n-missing.json")
REVIEW = ROOT / "docs/I18N_MACHINE_TRANSLATION_REVIEW.md"
LOCALES = ("en", "de", "fr", "pl", "es")
CYRILLIC = re.compile(r"[\u0400-\u04ff]")

def install_models():
    available = package.get_available_packages()
    for source, target in [("bg", "en"), ("en", "de"), ("en", "fr"), ("en", "pl"), ("en", "es")]:
        pair = next((item for item in available if item.from_code == source and item.to_code == target), None)
        if pair is None:
            raise RuntimeError(f"Argos model unavailable: {source}->{target}. No files have been modified.")
        print(f"Installing Argos {source}->{target}", flush=True)
        package.install_from_path(pair.download())

def translate_phrase(text, from_code, to_code):
    leading = len(text) - len(text.lstrip())
    trailing = len(text) - len(text.rstrip())
    core = text.strip()
    result = translate.translate(core, from_code, to_code).strip()
    if not result:
        raise ValueError(f"Empty translation for {from_code}->{to_code}")
    return text[:leading] + result + (text[len(text)-trailing:] if trailing else "")

def main():
    data = json.loads(CANDIDATES.read_text(encoding="utf-8"))
    candidates = data["entries"]
    if not candidates:
        print("No missing API translations.")
        return
    text = CATALOG.read_text(encoding="utf-8")
    anchor = "  'Активна':"
    if text.count(anchor) != 1:
        raise RuntimeError("Could not find unique catalog insertion point.")
    install_models()
    rows = []
    flagged = []
    failures = []
    for index, entry in enumerate(candidates, 1):
        source = entry["source"]
        try:
            english = translate_phrase(source, "bg", "en")
            translations = {"en": english}
            for lang in LOCALES[1:]:
                translations[lang] = translate_phrase(english, "en", lang)
            for lang, result in translations.items():
                if CYRILLIC.search(result):
                    # Proper names often remain untranslated; transliteration is a
                    # reviewable fallback, not evidence of idiomatic localization.
                    translations[lang] = re.sub(r"[\u0400-\u04ff]+", lambda m: unidecode(m.group(0)).strip(), result)
                    flagged.append((source, f"{lang}: transliteration needed"))
            if source != source.strip() or len(source.strip()) < 16:
                flagged.append((source, "short or fragmentary source; grammar needs review"))
            rendered = json.dumps(source, ensure_ascii=False) + ":{" + ",".join(
                lang + ":" + json.dumps(translations[lang], ensure_ascii=False)
                for lang in LOCALES
            ) + "},"
            rows.append("  " + rendered)
        except Exception as exc:
            failures.append((source, str(exc)[:120]))
        if index % 25 == 0:
            print(f"Translated {index}/{len(candidates)} candidates", flush=True)
    if not rows:
        raise RuntimeError("No translations generated. Catalog left untouched.")
    CATALOG.write_text(text.replace(anchor, "\n".join(rows)+"\n"+anchor), encoding="utf-8")
    lines = [
        "# CASEFILES offline translation review — NOT APPROVED",
        "",
        f"Source literals processed: **{len(candidates)}**.",
        f"New draft entries: **{len(rows)}**.",
        f"Translation failures: **{len(failures)}**.",
        f"Flagged for human review: **{len(flagged)}**.",
        "",
        "Generated by open-source Argos Translate via Bulgarian → English → target language.",
        "Translations have NOT been proofread and do NOT establish production readiness.",
        "Never use this output to claim native-level language quality or a complete localization.",
        "Game identifiers, solution IDs, server validations and player-authored stories were not changed.",
        "",
        "## Samples requiring manual review",
    ]
    for source, reason in flagged[:120]:
        lines.append(f"- {reason}: {source[:180]}")
    if failures:
        lines.append("\n## Untranslated candidates")
        for source, reason in failures[:200]:
            lines.append(f"- {source[:180]} — {reason}")
    REVIEW.write_text("\n".join(lines)+"\n", encoding="utf-8")
    print(f"Draft entries: {len(rows)}, failures: {len(failures)}, review flags: {len(flagged)}", flush=True)
    if failures:
        print("WARNING: untranslated candidates remain; see the review report.", flush=True)

if __name__ == "__main__":
    main()
